import java.io.PrintStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import java.util.function.IntPredicate;
import java.util.function.IntUnaryOperator;

/**
 * Writes the two tables of the code points above U+FFFF that GenerateTables does not cover, into
 * the directory given as the argument: code_point_tables.rs (categories and numeric values, and
 * the non-spacing marks of every plane, for regular expressions' word boundaries) and
 * code_point_case_tables.rs (case and alphabetic properties). Each table is sorted runs of code
 * points, so a range of letters or of one case mapping is one entry. Everything is read from the
 * JDK, so the tables are exact for the JDK that generates them.
 *
 * Usage: java crates/runtime/tables/GenerateCodePointTables.java crates/runtime/src
 */
public class GenerateCodePointTables {
    static final int FIRST = 0x1_0000;
    static final int LAST = 0x10_FFFF;

    public static void main(String[] args) throws Exception {
        String dir = args[0];
        PrintStream out = open(dir + "/code_point_tables.rs");
        out.println("//! Java's `Character` tables for the code points above U+FFFF, for the categories and the");
        out.println("//! numeric values (see `code_point_chars.rs`).");
        header(out);

        out.println("/// The code points that `Character.isLetter` accepts.");
        ranges(out, "LETTERS", c -> Character.isLetter(c));

        out.println("/// The code points of Unicode category Nd, which `Character.isDigit` accepts.");
        ranges(out, "DIGITS", c -> Character.isDigit(c));

        out.println("/// The code points with a numeric value, as `(first, last, offset)`: the value of `c` in");
        out.println("/// `first..=last` is `c + offset`. Fractions are in `FRACTIONS`.");
        offsets(out, "NUMERIC", c -> Character.getNumericValue(c), c -> Character.getNumericValue(c) >= 0);

        out.println("/// The code points whose numeric value is a fraction (`Character.getNumericValue` gives -2).");
        ranges(out, "FRACTIONS", c -> Character.getNumericValue(c) == -2);

        out.println("/// Every code point, in the BMP too, of Unicode category Mn (`Character.NON_SPACING_MARK`).");
        ranges(out, "NON_SPACING_MARKS", 0, c -> Character.getType(c) == Character.NON_SPACING_MARK);
        out.close();

        out = open(dir + "/code_point_case_tables.rs");
        out.println("//! Java's `Character` tables for the code points above U+FFFF, for the case mappings and the");
        out.println("//! case and alphabetic properties (see `code_point_chars.rs`).");
        header(out);

        out.println("/// The code points whose simple uppercase mapping is another code point, as `(first, last, offset)`.");
        offsets(out, "UPPER", c -> Character.toUpperCase(c), c -> Character.toUpperCase(c) != c);

        out.println("/// The code points whose simple lowercase mapping is another code point, as `(first, last, offset)`.");
        offsets(out, "LOWER", c -> Character.toLowerCase(c), c -> Character.toLowerCase(c) != c);

        out.println("/// The code points that `Character.isUpperCase` accepts.");
        ranges(out, "UPPERCASE", c -> Character.isUpperCase(c));

        out.println("/// The code points that `Character.isLowerCase` accepts.");
        ranges(out, "LOWERCASE", c -> Character.isLowerCase(c));

        out.println("/// The code points that `Character.isAlphabetic` accepts.");
        ranges(out, "ALPHABETIC", c -> Character.isAlphabetic(c));
        out.close();
    }

    static PrintStream open(String path) throws Exception {
        return new PrintStream(path, StandardCharsets.UTF_8);
    }

    static void header(PrintStream out) {
        out.println("//!");
        out.println("//! Generated by JDK " + Runtime.version() + " from the Character methods; do not edit.");
        out.println("//! Regenerate with `java crates/runtime/tables/GenerateCodePointTables.java crates/runtime/src`.");
        out.println();
    }

    /// Writes the runs of code points in the supplementary planes that satisfy `test`.
    static void ranges(PrintStream out, String name, IntPredicate test) {
        ranges(out, name, FIRST, test);
    }

    /// Writes the runs of code points from `first` on that satisfy `test`.
    static void ranges(PrintStream out, String name, int first, IntPredicate test) {
        out.println("pub(crate) static " + name + ": &[(u32, u32)] = &[");
        int start = -1;
        for (int c = first; c <= LAST + 1; c++) {
            boolean in = c <= LAST && test.test(c);
            if (in && start < 0) {
                start = c;
            } else if (!in && start >= 0) {
                out.printf("    (0x%X, 0x%X),%n", start, c - 1);
                start = -1;
            }
        }
        out.println("];");
        out.println();
    }

    /// Writes the runs of code points in the supplementary planes that `present` accepts, as
    /// `(first, last, offset)` where the value of `c` is `c + offset`. A run continues while the
    /// offset stays the same, so that a block of letters with one case mapping is one entry.
    static void offsets(PrintStream out, String name, IntUnaryOperator value, IntPredicate present) {
        List<int[]> runs = new ArrayList<>();
        for (int c = FIRST; c <= LAST; c++) {
            if (!present.test(c)) {
                continue;
            }
            int offset = value.applyAsInt(c) - c;
            int[] last = runs.isEmpty() ? null : runs.get(runs.size() - 1);
            if (last != null && last[1] == c - 1 && last[2] == offset) {
                last[1] = c;
            } else {
                runs.add(new int[] {c, c, offset});
            }
        }
        out.println("pub(crate) static " + name + ": &[(u32, u32, i32)] = &[");
        for (int[] run : runs) {
            out.printf("    (0x%X, 0x%X, %d),%n", run[0], run[1], run[2]);
        }
        out.println("];");
        out.println();
    }
}
