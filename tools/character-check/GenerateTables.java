import java.io.PrintStream;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.function.IntPredicate;

/**
 * Writes crates/runtime/src/character_tables.rs: the JDK's answers for the Character methods that
 * Rust's char methods do not give, as sorted ranges of code units rather than one entry per char.
 * Everything here is read from the JDK, so the table is exact for the JDK that generates it.
 *
 * Usage: java tools/character-check/GenerateTables.java > crates/runtime/src/character_tables.rs
 */
public class GenerateTables {
    public static void main(String[] args) {
        PrintStream out = System.out;
        out.println("//! Java's `Character` tables for the code units where Rust's `char` tables differ.");
        out.println("//!");
        out.println("//! Generated by JDK " + Runtime.version() + " from the Character methods; do not edit.");
        out.println("//! Regenerate with `java tools/character-check/GenerateTables.java > "
                + "crates/runtime/src/character_tables.rs`.");
        out.println();

        out.println("/// The code units of Unicode category Nd, which `Character.isDigit` accepts.");
        ranges(out, "DIGITS", c -> Character.isDigit(c));

        out.println("/// The code units that `Character.isLetter` accepts.");
        ranges(out, "LETTERS", c -> Character.isLetter(c));

        out.println("/// The code units with a numeric value, as `(first, last, offset)`: the value of `c` in");
        out.println("/// `first..=last` is `c + offset`. Fractions are in `FRACTIONS`.");
        numericOffsets(out);

        out.println("/// The code units whose numeric value is a fraction (`Character.getNumericValue` gives -2).");
        ranges(out, "FRACTIONS", c -> Character.getNumericValue(c) == -2);

        out.println("/// The code units whose simple uppercase mapping is not the one Rust's full mapping gives,");
        out.println("/// as `(code unit, uppercase)`: characters whose full uppercase mapping is several characters");
        out.println("/// (`ᾀ` becomes `ἈΙ`) but whose simple mapping is one.");
        upperCaseExceptions(out);
    }

    /// Writes the runs of code units that satisfy `test` as `(first, last)` pairs.
    static void ranges(PrintStream out, String name, IntPredicate test) {
        out.println("pub(crate) static " + name + ": &[(u16, u16)] = &[");
        int start = -1;
        for (int c = 0; c <= 0x10000; c++) {
            boolean in = c <= 0xFFFF && test.test(c);
            if (in && start < 0) {
                start = c;
            } else if (!in && start >= 0) {
                out.printf("    (0x%04X, 0x%04X),%n", start, c - 1);
                start = -1;
            }
        }
        out.println("];");
        out.println();
    }

    /// Writes the runs of code units with a numeric value as `(first, last, offset)`, where the
    /// value is the code unit plus the offset, so that a run of digits is one entry.
    static void numericOffsets(PrintStream out) {
        List<int[]> runs = new ArrayList<>();
        for (int c = 0; c <= 0xFFFF; c++) {
            int value = Character.getNumericValue(c);
            if (value < 0) {
                continue;
            }
            int offset = value - c;
            int[] last = runs.isEmpty() ? null : runs.get(runs.size() - 1);
            if (last != null && last[1] == c - 1 && last[2] == offset) {
                last[1] = c;
            } else {
                runs.add(new int[] {c, c, offset});
            }
        }
        out.println("pub(crate) static NUMERIC_OFFSETS: &[(u16, u16, i32)] = &[");
        for (int[] run : runs) {
            out.printf("    (0x%04X, 0x%04X, %d),%n", run[0], run[1], run[2]);
        }
        out.println("];");
        out.println();
    }

    /// Writes the code units whose simple uppercase mapping the runtime cannot get from Rust's
    /// `to_uppercase`, because the full mapping is several characters: `(code unit, uppercase)`.
    static void upperCaseExceptions(PrintStream out) {
        out.println("pub(crate) static UPPER_CASE_EXCEPTIONS: &[(u16, u16)] = &[");
        for (int c = 0; c <= 0xFFFF; c++) {
            int upper = Character.toUpperCase(c);
            String full = String.valueOf((char) c).toUpperCase(Locale.ROOT);
            if (upper != c && full.length() != 1) {
                out.printf("    (0x%04X, 0x%04X),%n", c, upper);
            }
        }
        out.println("];");
    }
}
